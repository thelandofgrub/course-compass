const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

const root = path.resolve(__dirname, '..');
const reportDir = path.join(root, 'release-assets', 'reports');

function loadGolfData() {
    const memory = new Map();
    const store = {
        getRaw: key => memory.get(key) ?? null,
        setRaw: (key, value) => memory.set(key, String(value)),
        remove: key => memory.delete(key),
        getJSON: (_key, fallback = null) => fallback,
        setJSON() {}
    };
    const sandbox = {
        console,
        CourseCompassStore: store,
        localStorage: { getItem: store.getRaw, setItem: store.setRaw, removeItem: store.remove },
        document: { createElement: () => ({ set textContent(value) { this.innerHTML = String(value); }, innerHTML: '' }) }
    };
    vm.createContext(sandbox);
    const openData = fs.readFileSync(path.join(root, 'js', 'course-data-open.js'), 'utf8');
    const master = fs.readFileSync(path.join(root, 'js', 'data.js'), 'utf8');
    vm.runInContext(`${openData}\n${master}\nglobalThis.__golfData = GolfData;`, sandbox);
    return sandbox.__golfData;
}

const data = loadGolfData();
const published = JSON.parse(fs.readFileSync(path.join(root, 'data', 'coursecompass-open-courses.json'), 'utf8'));
const errors = [];
const warnings = [];
const ids = new Set();
const allowedAvailability = new Set(['licensed-scorecard', 'licensed-mapped-scorecard', 'licensed-catalog-only', 'verified-reference-only']);

if (published.license !== 'ODbL-1.0' || !published.attribution?.includes('OpenStreetMap contributors')) errors.push('Published database must state ODbL-1.0 and OpenStreetMap attribution.');
if (JSON.stringify(published.courses) !== JSON.stringify(data.courses)) errors.push('Published JSON and runtime course snapshot differ.');
if (data.courses.length !== 50) errors.push(`Expected 50 resolved built-in records; found ${data.courses.length}.`);

for (const [courseIndex, course] of data.courses.entries()) {
    const label = course.name || `course ${courseIndex + 1}`;
    if (!course.id || ids.has(course.id)) errors.push(`${label}: missing or duplicate course id.`);
    ids.add(course.id);
    if (!course.name || !course.location) errors.push(`${label}: sourced name and location are required.`);
    if (!allowedAvailability.has(course.dataAvailability)) errors.push(`${label}: invalid or unresolved data-availability status.`);
    if (!course.source?.provider || !course.source?.license || !course.source?.attribution || !course.source?.url) errors.push(`${label}: provider, license, attribution, and source URL are required.`);
    if (course.dataAvailability !== 'verified-reference-only' && !/^ODbL-1\.0$/i.test(course.source?.license || '')) errors.push(`${label}: open course records must identify ODbL-1.0.`);

    const catalogOnly = ['licensed-catalog-only', 'verified-reference-only'].includes(course.dataAvailability);
    const holes = Array.isArray(course.holes) ? course.holes : [];
    if (catalogOnly && holes.length !== 0) errors.push(`${label}: catalog/reference-only records must not retain hole data.`);
    if (!catalogOnly && holes.length !== 18) errors.push(`${label}: licensed scorecard must contain 18 holes.`);
    if (catalogOnly) warnings.push(`${label}: intentionally catalog-only; no hole scorecard is displayed.`);

    const lat = Number(course.lat), lon = Number(course.lon);
    if (course.dataAvailability !== 'verified-reference-only' && (!Number.isFinite(lat) || lat < -90 || lat > 90 || !Number.isFinite(lon) || lon < -180 || lon > 180)) errors.push(`${label}: invalid sourced coordinates.`);
    if (course.rating != null && (!Number.isFinite(Number(course.rating)) || Number(course.rating) < 50 || Number(course.rating) > 90)) errors.push(`${label}: supplied rating is outside 50-90.`);
    if (course.slope != null && (!Number.isFinite(Number(course.slope)) || Number(course.slope) < 55 || Number(course.slope) > 155)) errors.push(`${label}: supplied slope is outside 55-155.`);

    const numbers = holes.map(hole => Number(hole.hole));
    if (new Set(numbers).size !== holes.length || numbers.some((hole, index) => hole !== index + 1)) errors.push(`${label}: hole numbers must be unique and sequential.`);
    for (const hole of holes) {
        const holeLabel = `${label}, hole ${hole.hole}`;
        if (!Number.isInteger(Number(hole.par)) || Number(hole.par) < 3 || Number(hole.par) > 6) errors.push(`${holeLabel}: par must be 3-6.`);
        if (!Number.isFinite(Number(hole.yards)) || Number(hole.yards) < 50 || Number(hole.yards) > 900) errors.push(`${holeLabel}: sourced/calculated yardage is outside 50-900.`);
        if (!/^Confirm the playing distance|^Choose a tee target|^Prioritize a playable approach/.test(hole.tip || '')) errors.push(`${holeLabel}: strategy text was not generated by the provenance-safe CourseCompass template.`);
        for (const point of hole.mapGeometry?.path || []) {
            if (!Number.isFinite(Number(point.lat)) || Number(point.lat) < -90 || Number(point.lat) > 90 || !Number.isFinite(Number(point.lon)) || Number(point.lon) < -180 || Number(point.lon) > 180) errors.push(`${holeLabel}: invalid OSM geometry point.`);
        }
    }
    const teeIds = new Set();
    for (const tee of course.tees || []) {
        if (!tee.id || teeIds.has(tee.id)) errors.push(`${label}: tee-set ids must be present and unique.`);
        teeIds.add(tee.id);
        const teeHoles = Array.isArray(tee.holes) ? tee.holes : [];
        if (teeHoles.length !== 18) errors.push(`${label}, ${tee.name || 'tee'}: only complete 18-hole tee sets may be published.`);
        if (teeHoles.some((hole, index) => Number(hole.hole) !== index + 1 || Number(hole.yards) < 40 || Number(hole.yards) > 900)) errors.push(`${label}, ${tee.name || 'tee'}: invalid hole sequence or yardage.`);
        const total = teeHoles.reduce((sum, hole) => sum + Number(hole.yards || 0), 0);
        if (tee.totalYardage && Number(tee.totalYardage) !== total) errors.push(`${label}, ${tee.name || 'tee'}: total yardage does not match its holes.`);
    }
}

const scorecards = data.courses.filter(course => course.holes.length === 18);
const report = {
    generatedAt: new Date().toISOString(),
    status: errors.length ? 'failed' : warnings.length ? 'passed-with-availability-warnings' : 'passed',
    scope: 'Resolved built-in snapshot only; imported and user-created records retain their own source metadata.',
    license: published.license,
    attribution: published.attribution,
    courseCount: data.courses.length,
    licensedScorecardCount: scorecards.length,
    catalogOrReferenceOnlyCount: data.courses.length - scorecards.length,
    holeCount: scorecards.reduce((total, course) => total + course.holes.length, 0),
    completeTeeSetCount: data.courses.reduce((total, course) => total + (course.tees || []).length, 0),
    unresolvedProvenanceCount: data.courses.filter(course => !allowedAvailability.has(course.dataAvailability)).length,
    errors,
    warnings
};
fs.mkdirSync(reportDir, { recursive: true });
fs.writeFileSync(path.join(reportDir, 'course-data-audit.json'), `${JSON.stringify(report, null, 2)}\n`);
console.log(JSON.stringify(report, null, 2));
if (errors.length) process.exitCode = 1;
